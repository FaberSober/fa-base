ALTER TABLE "base_job" ADD COLUMN IF NOT EXISTS "job_type" integer NOT NULL DEFAULT 0, ADD COLUMN IF NOT EXISTS "flow_definition" text;
COMMENT ON COLUMN "base_job"."job_type" IS '任务类型:0普通/1流程';
COMMENT ON COLUMN "base_job"."flow_definition" IS '流程定义JSON';

-- 流程节点直接引用注册类，无独立任务配置时 job_id 允许为空。
ALTER TABLE "base_job_log"
    ALTER COLUMN "job_id" DROP NOT NULL,
    ADD COLUMN IF NOT EXISTS "job_type" integer NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS "trigger_source" integer NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS "flow_snapshot" text,
    ADD COLUMN IF NOT EXISTS "clazz_path" varchar(255),
    ADD COLUMN IF NOT EXISTS "job_name" varchar(255);
COMMENT ON COLUMN "base_job_log"."job_id" IS '独立任务或流程配置ID，类路径节点可为空';
COMMENT ON COLUMN "base_job_log"."job_type" IS '本轮任务类型:0普通/1流程';
COMMENT ON COLUMN "base_job_log"."trigger_source" IS '触发来源:0历史/1手动/2Cron/3流程节点';
COMMENT ON COLUMN "base_job_log"."flow_snapshot" IS '本轮流程完整配置快照';
COMMENT ON COLUMN "base_job_log"."clazz_path" IS '执行类路径快照，历史记录可空';
COMMENT ON COLUMN "base_job_log"."job_name" IS '任务名称快照，历史记录可空';

CREATE TABLE IF NOT EXISTS "base_job_flow_node_run" (
    "id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "flow_log_id" integer NOT NULL,
    "node_id" varchar(100) NOT NULL,
    "clazz_path" varchar(255) NOT NULL,
    "node_name" varchar(255) NOT NULL,
    "attempt" integer NOT NULL DEFAULT 1,
    "job_log_id" integer DEFAULT NULL,
    "status" integer NOT NULL DEFAULT 0,
    "begin_time" timestamp(3) DEFAULT NULL,
    "end_time" timestamp(3) DEFAULT NULL,
    "reason" text,
    "crt_time" timestamp(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "upd_time" timestamp(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY ("id"),
    CONSTRAINT "uk_flow_node_attempt" UNIQUE ("flow_log_id", "node_id", "attempt"),
    CONSTRAINT "uk_flow_node_job_log" UNIQUE ("job_log_id")
);
CREATE INDEX IF NOT EXISTS "idx_flow_node_status" ON "base_job_flow_node_run" ("flow_log_id", "status");
CREATE INDEX IF NOT EXISTS "idx_flow_node_recovery" ON "base_job_flow_node_run" ("status", "upd_time");
COMMENT ON TABLE "base_job_flow_node_run" IS 'BASE-流程节点运行记录';
COMMENT ON COLUMN "base_job_flow_node_run"."id" IS '节点运行ID';
COMMENT ON COLUMN "base_job_flow_node_run"."flow_log_id" IS '所属流程执行记录ID';
COMMENT ON COLUMN "base_job_flow_node_run"."node_id" IS '本轮流程内独立节点ID';
COMMENT ON COLUMN "base_job_flow_node_run"."clazz_path" IS '引用的注册任务类路径快照';
COMMENT ON COLUMN "base_job_flow_node_run"."node_name" IS '节点名称快照';
COMMENT ON COLUMN "base_job_flow_node_run"."attempt" IS '尝试序号，首版固定1';
COMMENT ON COLUMN "base_job_flow_node_run"."job_log_id" IS '实际业务执行日志ID，未启动为空';
COMMENT ON COLUMN "base_job_flow_node_run"."status" IS '0等待依赖/10待调度/20启动中/30执行中/40成功/50失败/60阻断/70停止/80未确认';
COMMENT ON COLUMN "base_job_flow_node_run"."begin_time" IS '实际开始时间';
COMMENT ON COLUMN "base_job_flow_node_run"."end_time" IS '真实结束时间，未确认不伪造';
COMMENT ON COLUMN "base_job_flow_node_run"."reason" IS '失败、阻断、停止或未确认原因';
COMMENT ON COLUMN "base_job_flow_node_run"."crt_time" IS '创建时间';
COMMENT ON COLUMN "base_job_flow_node_run"."upd_time" IS '更新时间，由应用维护';
