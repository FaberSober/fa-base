package com.faber.api.base.admin.biz;

import com.alibaba.druid.DbType;
import com.alibaba.druid.sql.SQLUtils;
import com.faber.core.utils.SqlUtils;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.FileSystemResource;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.Statement;
import java.util.List;
import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.*;

/** 验证交付文件，不连接或修改用户数据库。 */
class JobDefinitionVersionSqlTest {
    private String parseable(String sql, String dialect) {
        // Druid当前不支持PG identity及PL/pgSQL RAISE；仅语法输入替换，真实分句器始终处理原始SQL。
        return dialect.equals("postgre") ? sql.replace("GENERATED BY DEFAULT AS IDENTITY", "")
                .replaceAll("(?s)" + java.util.regex.Pattern.quote("DO $$") + ".*?"
                        + java.util.regex.Pattern.quote("$$") + ";?", "SELECT 1;") : sql;
    }
    @Test void manualPatchHeadersAndStatementsAreValid() throws Exception {
        for (String dialect : List.of("mysql", "postgre")) {
            Path file = Path.of("docs/sql", dialect, "1.0.54_patch_job_definition_version.sql");
            assertEquals(1_000_054L, new SystemUpdateLogBiz().getSqlFileHeader(new FileSystemResource(file)).getVer());
            String sql = Files.readString(file);
            var db = dialect.equals("mysql") ? DbType.mysql : DbType.postgresql;
            var parsed = SQLUtils.parseStatements(parseable(sql, dialect), db);
            Connection connection = mock(Connection.class); Statement statement = mock(Statement.class);
            when(connection.createStatement()).thenReturn(statement);
            SqlUtils.executeSql(connection, sql);
            var captured = org.mockito.ArgumentCaptor.forClass(String.class);
            verify(statement, times(parsed.size())).execute(captured.capture());
            for (String part : captured.getAllValues()) assertEquals(1, SQLUtils.parseStatements(parseable(part, dialect), db).size());
            if (dialect.equals("postgre")) {
                assertEquals(1, captured.getAllValues().stream().filter(part -> part.contains("RAISE EXCEPTION")
                        && part.contains("END; $$")).count());
            }
            assertTrue(sql.contains("CREATE TABLE IF NOT EXISTS"));
            assertFalse(sql.toUpperCase().contains("INSERT INTO"));
            assertFalse(sql.toUpperCase().contains("DROP TABLE"));
            assertFalse(sql.toUpperCase().contains("DELETE FROM BASE_JOB WHERE"));
            assertTrue(sql.contains("parent.job_type = 1 AND parent.definition_version_id IS NULL"));
            assertTrue(sql.contains("child.trigger_source = 3"));
            assertTrue(sql.contains("node.job_log_id = child.id"));
            assertTrue(sql.contains("DELETE FROM base_job_log WHERE job_type = 1 AND definition_version_id IS NULL"));
            assertTrue(sql.contains("stats_since = CURRENT_TIMESTAMP"));
        }
    }
    @Test void completeAndManualScriptsShareTheSameVersionStructure() throws Exception {
        for (String dialect : List.of("mysql", "postgre")) {
            String complete = Files.readString(Path.of("src/main/resources/sql/fa-base", dialect, "1.0.54_base_job_flow_definition.sql"));
            String patch = Files.readString(Path.of("docs/sql", dialect, "1.0.54_patch_job_definition_version.sql"));
            String quote = dialect.equals("mysql") ? "`" : "\"";
            String tableStart = "CREATE TABLE IF NOT EXISTS " + quote + "base_job_definition_version" + quote;
            int start = complete.indexOf(tableStart), end = complete.indexOf(';', start);
            assertEquals(complete.substring(start, end), patch.substring(patch.indexOf(tableStart), patch.indexOf(';', patch.indexOf(tableStart))));
            for (String field : List.of("current_definition_version_id", "definition_version_id", "idx_job_current_definition_version", "idx_job_log_definition_version")) {
                assertTrue(complete.contains(field)); assertTrue(patch.contains(field));
            }
            assertTrue(patch.contains("flow_snapshot"));
            assertFalse(complete.contains("flow_snapshot"));
        }
    }
}
