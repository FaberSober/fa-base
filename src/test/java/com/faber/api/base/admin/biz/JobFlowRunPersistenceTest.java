    @AfterEach void cleanup() { BaseContextHandler.remove(); }
    private Job createFlow() {
        Job job = new Job(); job.setJobName("冻结流程"); job.setJobType(1); job.setClazzPath(""); job.setCron("0 * * * * ?");
        job.setFlowDefinition("""
          {"schemaVersion":1,"name":"流程","maxConcurrency":3,"nodes":[
          {"id":"a","name":"A","clazzPath":"com.faber.config.quartz.customer.JobDemo1","position":{"x":0,"y":0}},
          {"id":"b","name":"B","clazzPath":"com.faber.config.quartz.customer.JobDemo1","position":{"x":0,"y":100}},
          {"id":"c","name":"C","clazzPath":"com.faber.config.quartz.customer.JobDemo1","position":{"x":0,"y":200}},
          {"id":"d","name":"D","clazzPath":"com.faber.config.quartz.customer.JobDemo1","position":{"x":200,"y":0}}],
          "edges":[{"source":"a","target":"b"},{"source":"b","target":"c"}]}
          """);
        jobs.insert(job); return job;
    }
    private void complete(JobFlowRunStore.Launch launch, JobLogStatusEnum status) {
        JobLog log = launch.log(); log.setStatus(status); log.setDuration(0L); log.setTrackingVersion(status == JobLogStatusEnum.UNCONFIRMED ? 2 : 1);
        log.setDurationMs(status == JobLogStatusEnum.UNCONFIRMED ? null : 1L); log.setEndTime(status == JobLogStatusEnum.UNCONFIRMED ? null : new Date());
        assertTrue(biz.finishExecution(log)); assertTrue(store.completeNode(log)); assertFalse(store.completeNode(log));
    }
    @Test void serialClaimFreezesConfigurationAndCountsTheFlowOnce() {
        Job job = createFlow(); var view = store.begin(job.getId());
        assertEquals(4, view.nodes().size()); assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM base_job", Integer.class));
        assertThrows(BuzzException.class, () -> store.begin(job.getId()));
        job.setFlowDefinition("{}"); jobs.updateById(job);
        for (String id : List.of("a", "b", "c", "d")) {
            var launch = store.claim(view.log().getId()); assertEquals(id, launch.node().getNodeId());
            assertNull(launch.log().getJobId()); assertNull(store.claim(view.log().getId()));
            assertTrue(store.markRunning(launch.node().getId())); assertFalse(store.markRunning(launch.node().getId()));
            complete(launch, JobLogStatusEnum.DONE);
        }
        assertNull(store.claim(view.log().getId()));
        assertEquals(JobLogStatusEnum.DONE, store.view(view.log().getId()).log().getStatus());
        assertEquals(1L, jobs.selectById(job.getId()).getExecuteCount()); assertEquals(1L, jobs.selectById(job.getId()).getSuccessCount());
        assertEquals(5, jdbc.queryForObject("SELECT COUNT(*) FROM base_job_log", Integer.class));
    }
    @Test void failureBlocksOnlyDescendantsAndIndependentWorkContinues() {
        Job job = createFlow(); int id = store.begin(job.getId()).log().getId();
        complete(store.claim(id), JobLogStatusEnum.ERROR);
        var independent = store.claim(id); assertEquals("d", independent.node().getNodeId());
        complete(independent, JobLogStatusEnum.DONE); store.claim(id);
        var view = store.view(id); assertEquals(JobLogStatusEnum.ERROR, view.log().getStatus());
        assertEquals(List.of(50,60,60,40), view.nodes().stream().map(node -> node.getStatus()).toList());
        assertNull(view.nodes().get(1).getJobLogId()); assertNull(view.nodes().get(2).getJobLogId());
        assertEquals(1L, jobs.selectById(job.getId()).getFailCount());
    }
    @Test void unconfirmedAndRestartedWorkAreNeverAutomaticallyRerun() {
        Job job = createFlow(); int id = store.begin(job.getId()).log().getId();
        var launch = store.claim(id); assertTrue(store.markRunning(launch.node().getId()));
        store.recoverInterrupted();
        assertEquals(JobLogStatusEnum.UNCONFIRMED, store.view(id).log().getStatus());
        assertNull(store.view(id).log().getEndTime());
        assertEquals(List.of(80,60,60,60), store.view(id).nodes().stream().map(node -> node.getStatus()).toList());
        assertNull(store.claim(id)); assertThrows(BuzzException.class, () -> store.begin(job.getId()));
        assertFalse(store.markRunning(launch.node().getId()));
        assertThrows(BuzzException.class, () -> biz.removeById(launch.log().getId()));
        assertThrows(BuzzException.class, () -> biz.removeById(id));
    }
    @Test void simultaneousStartsCreateOnlyOneRound() throws Exception {
        Job job = createFlow();
        var pool = java.util.concurrent.Executors.newFixedThreadPool(2);
        var ready = new java.util.concurrent.CountDownLatch(2);
        var start = new java.util.concurrent.CountDownLatch(1);
        java.util.concurrent.Callable<Boolean> submit = () -> {
            BaseContextHandler.useAdmin(); ready.countDown(); start.await();
            try { store.begin(job.getId()); return true; }
            catch (BuzzException expected) { return false; }
            finally { BaseContextHandler.remove(); }
        };
        try {
            var first = pool.submit(submit); var second = pool.submit(submit);
            assertTrue(ready.await(5, java.util.concurrent.TimeUnit.SECONDS)); start.countDown();
            assertNotEquals(first.get(10, java.util.concurrent.TimeUnit.SECONDS), second.get(10, java.util.concurrent.TimeUnit.SECONDS));
            assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM base_job_log", Integer.class));
            assertEquals(4, jdbc.queryForObject("SELECT COUNT(*) FROM base_job_flow_node_run", Integer.class));
        } finally { start.countDown(); pool.shutdownNow(); }
    }

    @Test void runnerSubmitsAfterInitializationAndRealLifecycleAdvancesPersistentNodes() {
        Job job = createFlow();
        var runner = new com.faber.api.base.admin.flow.JobFlowRunner();
        var queue = new java.util.ArrayDeque<Runnable>();
        var calls = new java.util.concurrent.atomic.AtomicInteger();
        var factory = org.mockito.Mockito.mock(org.springframework.beans.factory.config.AutowireCapableBeanFactory.class);
        org.mockito.Mockito.when(factory.createBean(org.mockito.ArgumentMatchers.any(Class.class))).thenAnswer(invocation -> {
            var task = new com.faber.config.quartz.BaseJob() { @Override protected void run() { calls.incrementAndGet(); } };
            ReflectionTestUtils.setField(task, "jobLogBiz", biz); return task;
        });
        ReflectionTestUtils.setField(runner, "store", store);
        ReflectionTestUtils.setField(runner, "logBiz", biz);
        ReflectionTestUtils.setField(runner, "beanFactory", factory);
        ReflectionTestUtils.setField(runner, "executor", (java.util.concurrent.Executor) queue::add);
        runner.recover();
        var view = runner.start(job.getId());
        assertEquals(0, calls.get()); assertEquals(4, view.nodes().size());
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM base_job_log", Integer.class));
        int ticks = 0;
        while (!queue.isEmpty() && ticks++ < 10) queue.remove().run();
        assertTrue(queue.isEmpty()); assertEquals(4, calls.get());
        assertEquals(JobLogStatusEnum.DONE, store.view(view.log().getId()).log().getStatus());
        assertEquals(List.of(40,40,40,40), store.view(view.log().getId()).nodes().stream().map(node -> node.getStatus()).toList());
        org.mockito.Mockito.verify(factory, org.mockito.Mockito.times(4)).destroyBean(org.mockito.ArgumentMatchers.any());
    }

